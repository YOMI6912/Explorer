def font(size, bold=False):
    return ImageFont.truetype(FONT_BOLD if bold else FONT, size)

def wrap_by_pixel(draw, text, fnt, max_width):
    lines = []
    for paragraph in str(text).split("\n"):
        if paragraph == "":
            lines.append("")
            continue
        current = ""
        for ch in paragraph:
            trial = current + ch
            if current and draw.textbbox((0, 0), trial, font=fnt)[2] > max_width:
                lines.append(current)
                current = ch
            else:
                current = trial
        if current:
            lines.append(current)
    return lines

class PDF:
    def __init__(self):
        self.pages = []
        self.page_no = 0

    def new_page(self, title, subtitle=None):
        self.page_no += 1
        im = Image.new("RGB", (W, H), "white")
        d = ImageDraw.Draw(im)
        d.rectangle((0, 0, W, 150), fill="#123B5D")
        d.text((M, 42), title, font=font(44, True), fill="white")
        if subtitle:
            d.text((M, 170), subtitle, font=font(25), fill="#52616B")
        d.line((M, 225, W - M, 225), fill="#D7E2EA", width=3)
        self.im, self.d = im, d
        self.y = 270 if subtitle else 205

    def heading(self, text, level=1):
        size = 34 if level == 1 else 29
        color = "#123B5D" if level == 1 else "#176B87"
        self.d.text((M, self.y), text, font=font(size, True), fill=color)
        self.y += size + 18

    def paragraph(self, text, size=25, color="#222222", gap=16, bullet=None):
        fnt = font(size)
        prefix = (bullet + " ") if bullet else ""
        lines = wrap_by_pixel(self.d, prefix + text, fnt, W - 2 * M)
        for line in lines:
            self.d.text((M, self.y), line, font=fnt, fill=color)
            self.y += size + 9
        self.y += gap

    def box(self, label, text, fill="#F1F7FA"):
        fnt = font(24)
        lines = wrap_by_pixel(self.d, text, fnt, W - 2 * M - 55)
        h = 65 + len(lines) * 34 + 20
        self.d.rounded_rectangle((M, self.y, W - M, self.y + h), radius=14,
                                 fill=fill, outline="#B8D4DF", width=2)
        self.d.text((M + 25, self.y + 18), label, font=font(26, True), fill="#123B5D")
        yy = self.y + 60
        for line in lines:
            self.d.text((M + 25, yy), line, font=fnt, fill="#222222")
            yy += 34
        self.y += h + 22

    def footer(self):
        self.d.line((M, H - 105, W - M, H - 105), fill="#D7E2EA", width=2)
        self.d.text((M, H - 78), "ESP32-S3 Clinic Modular | รายงานฉบับพรีเซนต์", font=font(20), fill="#667781")
        label = f"หน้า {self.page_no}"
        tw = self.d.textbbox((0, 0), label, font=font(20))[2]
        self.d.text((W - M - tw, H - 78), label, font=font(20), fill="#667781")
        self.pages.append(self.im)

